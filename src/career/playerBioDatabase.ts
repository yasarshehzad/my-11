/**
 * Checks whether a player is an active modern player (must NEVER be an icon).
 */
export function isCurrentPlayer(name: string): boolean {
  const normKey = normalizePlayerNameKey(name);
  return CURRENT_PLAYERS_SET.has(normKey);
}

/**
 * Checks whether a player is a historical icon or legend.
 * Current players are strictly excluded.
 */
