/**
 * Checks whether a player is an active modern player (must NEVER be an icon).
 */
export function isCurrentPlayer(name: string): boolean {
  const normKey = normalizePlayerNameKey(name);
  return CURRENT_PLAYERS_SET.has(normKey);
}

/**
 * Checks whether a player is a historical icon or legend.
 * Current players are strictly excluded.
 */
export function isIconPlayer(name: string): boolean {
  if (isCurrentPlayer(name)) return false;
  const bio = getPlayerBio(name);
  return Boolean(bio.peakSeason);
}

/**
 * Verified Real-World Biometric & Profile Database
 * Loaded synchronously from public/data/player-bio-records.json in Node/Vitest,
 * and fetched lazily in the browser via ensurePlayerBiosLoaded().
 */
export const PLAYER_BIO_RECORDS: Record<string, PlayerBioInfo> = {};

let bioRecordsLoaded = false;
let bioRecordsPromise: Promise<void> | null = null;

function isNodeRuntime(): boolean {
  return typeof process !== "undefined" && Boolean(process.versions && process.versions.node);
}

function hydrateBioRecordsInNodeSync(): void {
  if (bioRecordsLoaded || !isNodeRuntime()) return;
  try {
    const nodeRequire = eval("require") as (id: string) => unknown;
    const fs = nodeRequire("fs") as { existsSync: (p: string) => boolean; readFileSync: (p: string, enc: string) => string };
    const path = nodeRequire("path") as { resolve: (...parts: string[]) => string };
    const jsonPath = path.resolve(process.cwd(), "public", "data", "player-bio-records.json");
    if (fs.existsSync(jsonPath)) {
      const parsed = JSON.parse(fs.readFileSync(jsonPath, "utf8")) as Record<string, PlayerBioInfo>;
      Object.assign(PLAYER_BIO_RECORDS, parsed);
      bioRecordsLoaded = true;
    }
  } catch (err) {
    console.warn("Could not synchronously load player-bio-records.json in Node:", err);
  }
}

hydrateBioRecordsInNodeSync();

let lastBioLoadError: string | null = null;

export async function ensurePlayerBiosLoaded(): Promise<boolean> {
  if (bioRecordsLoaded) return true;
  if (isNodeRuntime()) {
    hydrateBioRecordsInNodeSync();
    return bioRecordsLoaded;
  }
  if (typeof window === "undefined" || typeof fetch === "undefined") return bioRecordsLoaded;
  if (!bioRecordsPromise) {
    lastBioLoadError = null;
    bioRecordsPromise = fetch("/data/player-bio-records.json")
      .then(async (res) => {
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
        const parsed = (await res.json()) as Record<string, PlayerBioInfo>;
        Object.assign(PLAYER_BIO_RECORDS, parsed);
        bioRecordsLoaded = true;
      })
      .catch((err) => {
        const msg = err instanceof Error ? err.message : "Network error";
        lastBioLoadError = `Failed to load player biometrics (${msg})`;
        console.warn("Failed to fetch player-bio-records.json:", err);
      })
      .finally(() => {
        bioRecordsPromise = null;
      });
  }

  await bioRecordsPromise;
  return bioRecordsLoaded;
}

export function getPlayerBioLoadError(): string | null {
  return lastBioLoadError;
}

export function isPlayerBiosLoaded(): boolean {
  return bioRecordsLoaded;
}

/**
 * Retrieves authentic player biometrics with intelligent defaults.
 */
export function getPlayerBio(
  nameOrId: string,
  fallbackPosition: string = 'CM'
): PlayerBioInfo {
  const normKey = normalizePlayerNameKey(nameOrId);
  const found = PLAYER_BIO_RECORDS[normKey];
  if (found) {
    return { ...found };
  }

  // Check partial name match
  for (const [key, bio] of Object.entries(PLAYER_BIO_RECORDS)) {
    if (key.length >= 4 && (key === normKey || key.includes(normKey) || normKey.includes(key))) {
      return { ...bio };
    }
  }

  // Intelligent fallback for non-mapped players based on position
  const pos = fallbackPosition.toUpperCase();
  let defaultFoot: 'Right' | 'Left' | 'Both' = 'Right';
  if (pos === 'LB' || pos === 'LWB' || pos === 'LM' || pos === 'LW') {
    defaultFoot = 'Left';
  }

  let heightCm = 182;
  let weightKg = 76;
  if (pos === 'GK') {
    heightCm = 191;
    weightKg = 86;
  } else if (pos === 'CB') {
    heightCm = 188;
    weightKg = 83;
  } else if (['LB', 'RB', 'LWB', 'RWB'].includes(pos)) {
    heightCm = 178;
    weightKg = 73;
  } else if (pos === 'ST' || pos === 'CF') {
    heightCm = 185;
    weightKg = 80;
  } else if (['LM', 'RM', 'LW', 'RW'].includes(pos)) {
    heightCm = 176;
    weightKg = 71;
  }

  const isCurrent = isCurrentPlayer(nameOrId);
  return {
    preferredFoot: defaultFoot,
    heightCm,
    weightKg,
    birthYear: isCurrent ? 2000 : 1975,
    peakAge: 26,
  };
}
