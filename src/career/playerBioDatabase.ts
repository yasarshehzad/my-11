// Normalized player lookup key: lowercase, stripped punctuation
export function normalizePlayerNameKey(name: string): string {
  return name
    .replace(/\s+\d{2}\/\d{2}$/, '')
    .replace(/\s+\d{4}$/, '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]/g, '')
    .trim();
}

