/**
 * Retrieves authentic player biometrics with intelligent defaults.
 */
export function getPlayerBio(
  nameOrId: string,
  fallbackPosition: string = 'CM'
): PlayerBioInfo {
  const normKey = normalizePlayerNameKey(nameOrId);
  const found = PLAYER_BIO_RECORDS[normKey];
  if (found) {
    return { ...found };
  }

  // Check partial name match
  for (const [key, bio] of Object.entries(PLAYER_BIO_RECORDS)) {
    if (key.length >= 4 && (key === normKey || key.includes(normKey) || normKey.includes(key))) {
      return { ...bio };
    }
  }

  // Intelligent fallback for non-mapped players based on position
  const pos = fallbackPosition.toUpperCase();
  let defaultFoot: 'Right' | 'Left' | 'Both' = 'Right';
  if (pos === 'LB' || pos === 'LWB' || pos === 'LM' || pos === 'LW') {
    defaultFoot = 'Left';
  }

  let heightCm = 182;
  let weightKg = 76;
  if (pos === 'GK') {
    heightCm = 191;
    weightKg = 86;
  } else if (pos === 'CB') {
    heightCm = 188;
    weightKg = 83;
  } else if (['LB', 'RB', 'LWB', 'RWB'].includes(pos)) {
    heightCm = 178;
    weightKg = 73;
  } else if (pos === 'ST' || pos === 'CF') {
    heightCm = 185;
    weightKg = 80;
  } else if (['LM', 'RM', 'LW', 'RW'].includes(pos)) {
    heightCm = 176;
    weightKg = 71;
  }

  const isCurrent = isCurrentPlayer(nameOrId);
  return {
    preferredFoot: defaultFoot,
    heightCm,
    weightKg,
    birthYear: isCurrent ? 2000 : 1975,
    peakAge: 26,
  };
}
